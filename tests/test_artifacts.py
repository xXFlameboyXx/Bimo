class TestArtifactToolsAndPermissions(unittest.TestCase):
    """Test tool registry, risk levels, confirmation policy, and execution results."""

    def setUp(self):
        self.test_dir = tempfile.mkdtemp(prefix="bimo_tools_test_")
        self.service = ArtifactService(workspace_dir=self.test_dir)
        self.registry = ToolRegistry()
        self.mock_image_provider = MockImageProvider()
        self.local_renderer = DeterministicLocalImageRenderer()
        register_artifact_tools(
            self.registry,
            self.service,
            self.mock_image_provider,
            self.local_renderer,
        )

    def tearDown(self):
        if os.path.exists(self.test_dir):
            shutil.rmtree(self.test_dir)

    def test_tools_registered(self):
        expected_tools = [
            "artifact.create_text",
            "artifact.create_markdown",
            "artifact.create_json",
            "artifact.create_csv",
            "artifact.create_docx",
            "artifact.create_pdf",
            "artifact.create_xlsx",
            "artifact.save_image",
            "artifact.list",
            "artifact.get_info",
            "image.generate",
            "image.render_local",
        ]
        registered = self.registry.list_names()
        for name in expected_tools:
            self.assertIn(name, registered)

    def test_permission_policy_confirm_required(self):
        confirm_tools = [
            "artifact.create_text",
            "artifact.create_markdown",
            "artifact.create_json",
            "artifact.create_csv",
            "artifact.create_docx",
            "artifact.create_pdf",
            "artifact.create_xlsx",
            "artifact.save_image",
            "image.generate",
            "image.render_local",
        ]
        for t_name in confirm_tools:
            tool = self.registry.get(t_name)
            self.assertEqual(tool.permission, ToolPermission.CONFIRM)

        # Read-only metadata tools should be safe
        safe_tools = ["artifact.list", "artifact.get_info"]
        for t_name in safe_tools:
            tool = self.registry.get(t_name)
            self.assertEqual(tool.permission, ToolPermission.SAFE)

    def test_execute_create_pdf_tool(self):
        result = self.registry.execute(
            "artifact.create_pdf",
            context={"confirmed": True},
            filename="bimo_doc.pdf",
            title="Bimo Document",
            sections=[
                {"type": "heading", "level": 1, "text": "Intro"},
                {"type": "paragraph", "text": "This is a real PDF generated by Bimo."},
            ],
        )
        self.assertTrue(result.success)
        self.assertEqual(result.metadata["filename"], "bimo_doc.pdf")
        self.assertEqual(result.metadata["mime_type"], "application/pdf")
        self.assertTrue(os.path.exists(result.metadata["path"]))

    def test_execute_create_xlsx_tool(self):
        result = self.registry.execute(
            "artifact.create_xlsx",
            context={"confirmed": True},
            filename="test_sheet.xlsx",
            sheets=[
                {
                    "name": "Phase 9",
                    "columns": ["Module", "Progress"],
                    "rows": [["Artifacts", "100%"]],
                }
            ],
        )
        self.assertTrue(result.success)
        self.assertEqual(result.metadata["mime_type"], "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")
        self.assertTrue(os.path.exists(result.metadata["path"]))

    def test_execute_image_generate_tool(self):
        result = self.registry.execute(
            "image.generate",
            context={"confirmed": True},
            prompt="A friendly desktop companion robot named Bimo",
            filename="bimo_robot.png",
        )
        self.assertTrue(result.success)
        self.assertEqual(result.metadata["mime_type"], "image/png")
        self.assertTrue(os.path.exists(result.metadata["path"]))


class TestArtifactPlanner(unittest.TestCase):
    """Test intent classification, visual-first planning, and image heuristics."""

    def test_intent_detection(self):
        self.assertEqual(
            ArtifactPlanner.detect_intent("Give me a graphical visual example on how to build a Minecraft base."),
            ArtifactIntent.VISUAL_GUIDE,
        )
        self.assertEqual(
            ArtifactPlanner.detect_intent("Make an illustrated guide for cottage build."),
            ArtifactIntent.VISUAL_GUIDE,
        )
        self.assertEqual(
            ArtifactPlanner.detect_intent("Create a presentation about my project."),
            ArtifactIntent.PRESENTATION,
        )
        self.assertEqual(
            ArtifactPlanner.detect_intent("Draw an architecture diagram of Bimo."),
            ArtifactIntent.INFOGRAPHIC,
        )
        self.assertEqual(
            ArtifactPlanner.detect_intent("Create an image of a cute woodland cottage."),
            ArtifactIntent.IMAGE,
        )
        self.assertEqual(
            ArtifactPlanner.detect_intent("Create an Excel budget sheet."),
            ArtifactIntent.SPREADSHEET,
        )
        self.assertEqual(
            ArtifactPlanner.detect_intent("Write a textual report about Minecraft bases."),
            ArtifactIntent.STRUCTURED_DOCUMENT,
        )

    def test_image_count_heuristics(self):
        # Default for visual guide: exactly 1 hero image
        self.assertEqual(
            ArtifactPlanner.determine_image_count("Show me a visual guide", ArtifactIntent.VISUAL_GUIDE),
            1,
        )
        self.assertEqual(
            ArtifactPlanner.determine_image_count("Give me one beautiful visual example", ArtifactIntent.VISUAL_GUIDE),
            1,
        )
        # Textual requests: 0 images
        self.assertEqual(
            ArtifactPlanner.determine_image_count("Write a textual report", ArtifactIntent.STRUCTURED_DOCUMENT),
            0,
        )
        # Explicit step-by-step images
        self.assertEqual(
            ArtifactPlanner.determine_image_count("Give me step-by-step illustrations", ArtifactIntent.VISUAL_GUIDE),
            3,
        )

    def test_minecraft_plan_synthesis(self):
        plan = ArtifactPlanner.create_plan("Give me a graphical visual example of how to build a Minecraft base.")
        self.assertEqual(plan.intent, ArtifactIntent.VISUAL_GUIDE)
        self.assertEqual(plan.style, "minecraft")
        self.assertEqual(plan.image_count, 1)
        self.assertTrue(len(plan.visual_assets) == 1)
        self.assertIn("Oak", plan.visual_assets[0].prompt)
        self.assertTrue(len(plan.callouts) > 0)
        self.assertTrue(len(plan.tips) > 0)


