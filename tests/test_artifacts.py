class TestArtifactGenerators(unittest.TestCase):
    """Test deterministic generation functions for all formats."""

    def test_generate_text(self):
        content = "Hello, Bimo!"
        raw = generate_text(content)
        self.assertEqual(raw, content.encode("utf-8"))

    def test_generate_markdown(self):
        content = "# Title\n\n- item 1\n- item 2"
        raw = generate_markdown(content)
        self.assertEqual(raw, content.encode("utf-8"))

    def test_generate_json(self):
        data = {"name": "Bimo", "version": 1.0, "active": True}
        raw = generate_json(data, indent=2)
        parsed = json.loads(raw.decode("utf-8"))
        self.assertEqual(parsed, data)

    def test_generate_csv_valid(self):
        columns = ["name", "role", "power"]
        rows = [["Bimo", "Robot", 100], ["Paneer", "Creator", 999]]
        raw = generate_csv(columns, rows)
        text = raw.decode("utf-8")
        self.assertIn("name,role,power", text)
        self.assertIn("Bimo,Robot,100", text)
        self.assertIn("Paneer,Creator,999", text)

    def test_generate_csv_mismatched_rows(self):
        columns = ["a", "b"]
        rows = [["1", "2"], ["3"]]  # 1 item instead of 2
        with self.assertRaises(ValueError):
            generate_csv(columns, rows)

    def test_generate_docx_structure(self):
        title = "Test Bimo Doc"
        sections = [
            {"type": "heading", "level": 1, "text": "Overview"},
            {"type": "paragraph", "text": "This is a document generated by Bimo."},
            {"type": "bullet", "text": "Point A"},
            {"type": "numbered", "text": "Step 1"},
            {"type": "table", "headers": ["Col1", "Col2"], "rows": [["Val1", "Val2"]]},
        ]
        raw = generate_docx(title, sections)
        self.assertTrue(len(raw) > 500)
        # Verify valid ZIP/DOCX structure
        with tempfile.NamedTemporaryFile(suffix=".docx", delete=False) as tmp:
            tmp.write(raw)
            tmp_path = tmp.name
        try:
            self.assertTrue(zipfile.is_zipfile(tmp_path))
            with zipfile.ZipFile(tmp_path) as z:
                names = z.namelist()
                self.assertIn("word/document.xml", names)
        finally:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)

    def test_generate_pdf_structure(self):
        title = "Bimo Architecture Specification"
        sections = [
            {"type": "heading", "level": 1, "text": "Core Subsystems"},
            {"type": "paragraph", "text": "Bimo operates on a multi-agent loop with tool confirmation."},
            {"type": "bullet", "text": "Artifact Service"},
            {"type": "bullet", "text": "PC Automation"},
            {"type": "table", "headers": ["Subsystem", "Status"], "rows": [["Artifacts", "Active"], ["PC", "Active"]]},
            {"type": "pagebreak"},
            {"type": "heading", "level": 2, "text": "Phase Details"},
            {"type": "paragraph", "text": "Page two content for multi-page test."},
        ]
        raw = generate_pdf(title, sections, author="spinach")
        self.assertTrue(raw.startswith(b"%PDF-"))
        self.assertTrue(len(raw) > 1000)

    def test_generate_xlsx_structure(self):
        sheets = [
            {
                "name": "Phase Roadmap",
                "columns": ["Phase", "Name", "Status"],
                "rows": [
                    [1, "Core Pipeline", "Done"],
                    [2, "OmniRoute & LLM", "Done"],
                    [8, "PC Agent Refinement", "Done"],
                ],
            },
            {
                "name": "Metrics",
                "columns": ["Metric", "Value"],
                "rows": [["Latency", "50ms"], ["Accuracy", "100%"]],
            },
        ]
        raw = generate_xlsx(sheets)
        self.assertTrue(len(raw) > 1000)
        # Verify valid ZIP/XLSX structure
        with tempfile.NamedTemporaryFile(suffix=".xlsx", delete=False) as tmp:
            tmp.write(raw)
            tmp_path = tmp.name
        try:
            self.assertTrue(zipfile.is_zipfile(tmp_path))
            with zipfile.ZipFile(tmp_path) as z:
                names = z.namelist()
                self.assertIn("xl/workbook.xml", names)
        finally:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)

    def test_validate_and_process_image(self):
        renderer = DeterministicLocalImageRenderer()
        png_data = renderer.render_badge("BIMO", "ONLINE", "#10B981")
        processed = validate_and_process_image(png_data, "png")
        self.assertTrue(len(processed) > 0)
        self.assertTrue(processed.startswith(b"\x89PNG\r\n\x1a\n"))


class TestArtifactService(unittest.TestCase):
    """Test isolation, anti-traversal security, collision avoidance, and size limits."""

    def setUp(self):
        self.test_dir = tempfile.mkdtemp(prefix="bimo_test_artifacts_")
        self.service = ArtifactService(
            workspace_dir=self.test_dir,
            max_artifact_size_mb=1,
            max_text_size_mb=1,
            max_image_size_mb=1,
        )

    def tearDown(self):
        if os.path.exists(self.test_dir):
            shutil.rmtree(self.test_dir)

    def test_create_and_list_artifact(self):
        art = self.service.create_artifact(
            filename="report.txt",
            data=b"Hello Bimo Artifact System",
            mime_type="text/plain",
            metadata={"tag": "unit_test"},
        )
        self.assertTrue(art.id.startswith("artifact-"))
        self.assertEqual(art.filename, "report.txt")
        self.assertTrue(os.path.exists(art.path))

        listed = self.service.list_artifacts()
        self.assertEqual(len(listed), 1)
        self.assertEqual(listed[0].id, art.id)

        fetched = self.service.get_artifact(art.id)
        self.assertIsNotNone(fetched)
        self.assertEqual(fetched.filename, "report.txt")

    def test_non_destructive_naming(self):
        art1 = self.service.create_artifact("doc.md", b"# Title 1", "text/markdown")
        art2 = self.service.create_artifact("doc.md", b"# Title 2", "text/markdown")
        art3 = self.service.create_artifact("doc.md", b"# Title 3", "text/markdown")

        self.assertEqual(art1.filename, "doc.md")
        self.assertEqual(art2.filename, "doc (1).md")
        self.assertEqual(art3.filename, "doc (2).md")

        self.assertTrue(os.path.exists(art1.path))
        self.assertTrue(os.path.exists(art2.path))
        self.assertTrue(os.path.exists(art3.path))

    def test_security_path_traversal_relative(self):
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("../secret.txt", b"evil", "text/plain")

    def test_security_path_traversal_windows_absolute(self):
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("C:\\Windows\\System32\\bad.dll", b"evil", "text/plain")

    def test_security_path_traversal_unix_absolute(self):
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("/etc/passwd", b"evil", "text/plain")

    def test_security_invalid_characters(self):
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("test<file>.txt", b"evil", "text/plain")
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("test\0file.txt", b"evil", "text/plain")

    def test_security_unsupported_extension(self):
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("script.exe", b"binary", "application/octet-stream")
        with self.assertRaises(ArtifactSecurityError):
            self.service.create_artifact("payload.py", b"print(1)", "text/x-python")

    def test_size_limit_enforcement(self):
        # 1MB limit set in setUp
        oversized = b"X" * (1024 * 1024 + 10)
        with self.assertRaises(ArtifactSizeLimitError):
            self.service.create_artifact("large.txt", oversized, "text/plain")


